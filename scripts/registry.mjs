// scripts/registry.mjs
// Writes lib/registry.generated.mjs (gitignored): each site's vertical, brand
// and partner assignments, each vertical's scoring rules, and the partner
// directory from private/partners.json. The lead API imports it, so one
// deployed function can score and route leads for any site.
// Regenerated on every build. It contains partner contact details, so it is
// only ever bundled into the server-side function, never into public pages.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, SITES_DIR, VERTICALS_DIR, readJSON } from '../lib/core.mjs';
import { loadPartners, hashToken, consentName } from '../lib/partners.mjs';

export function writeRegistry() {
  const sites = {};
  if (fs.existsSync(SITES_DIR)) {
    for (const slug of fs.readdirSync(SITES_DIR)) {
      const f = path.join(SITES_DIR, slug, 'site.json');
      if (!fs.existsSync(f)) continue;
      const s = readJSON(f);
      sites[s.slug] = {
        vertical: s.vertical, brand: s.brand, domain: s.domain,
        buyers: s.buyers.map(b => b.name),
        operator: { name: s.operator?.legalName, address: s.operator?.address, email: s.operator?.email },
        bookingUrl: s.bookingUrl || '',
        partners: s.partners || []
      };
    }
  }
  const verticals = {};
  for (const f of fs.readdirSync(VERTICALS_DIR).filter(f => f.endsWith('.json'))) {
    const v = readJSON(path.join(VERTICALS_DIR, f));
    const labels = Object.fromEntries(v.form.steps.flatMap(st => st.fields).map(fl => [fl.name, fl.label]));
    const services = Object.fromEntries(v.services.map(sv => [sv.slug, sv.name]));
    verticals[v.id] = { label: v.label, scoring: v.scoring, labels, services };
  }
  const partners = {};
  for (const [id, p] of Object.entries(loadPartners())) {
    const { portalToken, ...rest } = p;
    partners[id] = { ...rest, consentName: consentName(p), tokenHash: portalToken ? hashToken(portalToken) : '' };
  }
  const out = path.join(ROOT, 'lib', 'registry.generated.mjs');
  fs.writeFileSync(out, `// AUTO-GENERATED by scripts/registry.mjs — do not edit or commit.\nexport default ${JSON.stringify({ sites, verticals, partners }, null, 2)};\n`);
  return out;
}

if (process.argv[1]?.endsWith('registry.mjs')) console.log('wrote', writeRegistry());
