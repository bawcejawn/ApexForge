// scripts/registry.mjs
// Writes lib/registry.generated.mjs: every site's vertical + buyers and every
// vertical's scoring rules. The lead API imports it, so one deployed function
// can validate and score leads for any site. Regenerated on every build.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, SITES_DIR, VERTICALS_DIR, readJSON } from '../lib/core.mjs';

export function writeRegistry() {
  const sites = {};
  if (fs.existsSync(SITES_DIR)) {
    for (const slug of fs.readdirSync(SITES_DIR)) {
      const f = path.join(SITES_DIR, slug, 'site.json');
      if (!fs.existsSync(f)) continue;
      const s = readJSON(f);
      sites[s.slug] = { vertical: s.vertical, brand: s.brand, buyers: s.buyers.map(b => b.name) };
    }
  }
  const verticals = {};
  for (const f of fs.readdirSync(VERTICALS_DIR).filter(f => f.endsWith('.json'))) {
    const v = readJSON(path.join(VERTICALS_DIR, f));
    verticals[v.id] = { scoring: v.scoring };
  }
  const out = path.join(ROOT, 'lib', 'registry.generated.mjs');
  fs.writeFileSync(out, `// AUTO-GENERATED by scripts/registry.mjs — do not edit.\nexport default ${JSON.stringify({ sites, verticals }, null, 2)};\n`);
  return out;
}
